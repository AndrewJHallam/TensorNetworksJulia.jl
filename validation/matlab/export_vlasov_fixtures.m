function export_vlasov_fixtures(tdvp)
% Extract original local functions without modifying the MATLAB source tree.
here = fileparts(mfilename('fullpath'));
project = fileparts(fileparts(here));
if nargin < 1 || isempty(tdvp)
    tdvp = getenv('TDVP_MATLAB_ROOT');
    if isempty(tdvp), tdvp = fileparts(project); end
end
relative_source = fullfile('mps-miscellany', 'Finite', 'Finite TDVP', 'INSE', ...
    'INSE_example_vlasov_poisson_scarfinder.m');
source_dir = fileparts(fullfile(tdvp, relative_source));
source_path = fullfile(source_dir, 'INSE_example_vlasov_poisson_scarfinder.m');
assert(isfile(source_path), ...
    'MATLAB source not found. Supply the TDVP root or set TDVP_MATLAB_ROOT.');
source = fileread(source_path);
output = fullfile(project, 'test', 'fixtures', 'vlasov_matlab');
if ~exist(output, 'dir'), mkdir(output); end
reference_path = fullfile(output, 'vlasov_matlab_reference.m');
fid = fopen(reference_path, 'w');
fprintf(fid, ['function [evolved,raw,corrected] = vlasov_matlab_reference(f0,x,v,dt,steps,levels,chi)\n', ...
    'out = evolve_vlasov_poisson(f0,x,v,dt,steps,steps);\n', ...
    'evolved = out.f{end};\n', ...
    'raw = truncate_grid_via_mps(evolved,levels,chi);\n', ...
    'corrected = truncate_to_manifold_vp(evolved,levels,chi,x,v,vlasov_mass(f0,x,v),vlasov_momentum(f0,x,v));\n', ...
    'end\n']);
fprintf(fid, '%s', segment(source, 'function out = evolve_vlasov_poisson(', ...
    'function [probe_times, center_entropy, max_entropy, f_start, f_end, f_history]'));
fprintf(fid, '%s', segment(source, 'function field_out = truncate_grid_via_mps(', ...
    'function selftest_results = vlasov_poisson_selftest()'));
fclose(fid);
addpath(output);
cleanup = onCleanup(@() rmpath(output)); %#ok<NASGU>
levels = 4; n = 2^levels; dt = 0.02; steps = 5; chi = 2;
x = (0:n-1)' * (2*pi/n); v = -6 + (0:n-1) * (12/n);
[X,V] = ndgrid(x,v);
f0 = (1 + 0.2*cos(X)) .* (exp(-0.5*((V-2.4)/0.4).^2) + ...
    exp(-0.5*((V+2.4)/0.4).^2)) / (2*sqrt(2*pi)*0.4);
[evolved,raw,corrected] = vlasov_matlab_reference(f0,x,v,dt,steps,levels,chi);
writematrix(f0, fullfile(output,'initial.csv'));
writematrix(evolved, fullfile(output,'evolved.csv'));
writematrix(raw, fullfile(output,'raw_projection.csv'));
writematrix(corrected, fullfile(output,'corrected_projection.csv'));

% A previously saved two-stream run provides an independent full-run target.
saved_name = 'vlasov_poisson_scarfinder_VP_S2_L7_chi4_tau100_20260427_143418.mat';
saved_path = fullfile(source_dir,'outputs','vlasov_poisson','data',saved_name);
if isfile(saved_path)
saved = load(saved_path, 'results');
r = saved.results;
baseline = fullfile(project, 'validation', 'results', 'vlasov_baseline');
if ~exist(baseline,'dir'), mkdir(baseline); end
writematrix(r.f_history{1}, fullfile(baseline,'matlab_saved_initial.csv'));
writematrix(r.f_history{end}, fullfile(baseline,'matlab_saved_final.csv'));
p = r.parameters;
params = table(p.levels,p.domain_length_x,p.velocity_max,p.dt,p.num_steps_tau, ...
    p.num_iterations,p.project_bond_dim,p.perturbation_amplitude,p.num_streams, ...
    p.stream_velocity,p.thermal_width, ...
    'VariableNames',{'levels','Lx','vmax','dt','steps_per_iteration','iterations','maxdim', ...
    'alpha','num_streams','speed','width'});
writetable(params, fullfile(baseline,'matlab_saved_parameters.csv'));
stats = table(r.step_error_history(end),r.final_cycle_periodicity_error, ...
    r.final_cycle_max_constancy_error, ...
    'VariableNames',{'step_error','cycle_error','maximum_motion'});
writetable(stats,fullfile(baseline,'matlab_saved_diagnostics.csv'));
disp(params);
disp(stats);
else
    fprintf('Optional historical dataset absent; exported small test fixtures only.\n');
end
fid = fopen(fullfile(output,'provenance.txt'),'w');
fprintf(fid,'Generated by MATLAB %s\nOriginal local routines extracted from:\n%s (relative to the original TDVP source tree)\n',version,relative_source);
fprintf(fid,'Small fixture: L=4, Lx=2*pi, vmax=6, dt=0.02, steps=5, chi=2, alpha=0.2, streams=2, speed=2.4, width=0.4\n');
fprintf(fid,'Full-run comparison target: %s\n',saved_name);
fclose(fid);
fprintf('Exported Vlasov MATLAB fixtures to %s\n',output);
end

function value = segment(source,start_marker,end_marker)
first = strfind(source,start_marker);
last = strfind(source,end_marker);
assert(numel(first)==1 && numel(last)==1 && last > first, 'Ambiguous source markers');
value = source(first:last-1);
end
