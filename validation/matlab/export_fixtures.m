function export_fixtures(output_dir, tdvp)
% Run original MATLAB routines on deterministic tensors. Sources stay read-only.
here = fileparts(mfilename('fullpath'));
project = fileparts(fileparts(here));
if nargin < 2 || isempty(tdvp)
    tdvp = getenv('TDVP_MATLAB_ROOT');
    if isempty(tdvp), tdvp = fileparts(project); end
end
finite = fullfile(tdvp, 'mps-miscellany', 'Finite', 'Finite TDVP');
infinite = fullfile(tdvp, 'mps-miscellany', 'infiniteChain');
addpath(fullfile(finite, 'General'), fullfile(finite, '1_site_scheme'), ...
    fullfile(finite, '2_site_scheme'), fullfile(infinite, 'stateManipulations'), ...
    fullfile(infinite, 'VUMPS'));
if nargin < 1 || isempty(output_dir)
    output_dir = fullfile(project, 'test', 'fixtures', 'matlab');
end
assert(isfile(fullfile(finite,'General','ncon.m')) && ...
       isfile(fullfile(infinite,'VUMPS','vumps.m')), ...
       'MATLAB sources not found. Supply the TDVP root or set TDVP_MATLAB_ROOT.');
if ~exist(output_dir, 'dir'), mkdir(output_dir); end
rng(781, 'twister'); % Solver seeds only; tensors use explicit formulas.
N = 6; dims = [1 2 3 4 3 2 1];
psi = cell(1, N);
for n = 1:N
    psi{n} = deterministic([dims(n), dims(n+1), 2], n);
end
% Centre at the right edge, as required by the original sweeps.
for n = 1:N-1
    [gauge, psi{n}] = l_orth(psi{n});
    psi{n+1} = ncon({gauge, psi{n+1}}, {[-1 1], [1 -2 -3]});
end
psi{N} = psi{N}/norm(psi{N}(:));
for n = 1:N, emit(output_dir, sprintf('psi%d',n), psi{n}); end
H = ising_mpox(N, -0.83, 0.27, 0, -0.61, 0.04);
for n = 1:N, emit(output_dir, sprintf('mpo%d',n), H{n}); end
emit(output_dir, 'energy', measure_mpo(psi, H, N));
% Y exposes the original measurement's transposed operator convention.
Y = [0 -1i; 1i 0];
emit(output_dir, 'measure_y_transposed', measure_o(psi, Y, N));
FL = cell(1,N+1); FR = cell(1,N+1); FL{1}=1; FR{N+1}=1;
for n=1:N, FL{n+1}=update_left_env(psi{n},H{n},FL{n}); end
for n=N:-1:1, FR{n}=update_right_env(psi{n},H{n},FR{n+1}); end
emit(output_dir, 'left3', FL{4}); emit(output_dir, 'right3', FR{3});
emit(output_dir, 'heff3', reshape(apply_H_to_A(psi{3}(:),FL{3},FR{4},H{3}),size(psi{3})));
AA = ncon({psi{3},psi{4}}, {[-1 1 -3],[1 -2 -4]});
emit(output_dir, 'heff34', reshape(apply_HH_to_AA(AA(:),FL{3},FR{5},H{3},H{4}),size(AA)));
params = struct('time','real','tol',1e-12,'maxiter',300,'krylovdim',30);
[evolved,~] = tdvp_finite_2site(psi,H,0.017,N,8,params);
emit(output_dir, 'tdvp2_state', dense_state(evolved));
evolved1 = tdvp_finite(psi,H,0.017,N,params);
emit(output_dir, 'tdvp1_state', dense_state(evolved1));
ground1 = dmrg_finite(psi,H,N);
emit(output_dir, 'dmrg1_state', dense_state(ground1));
emit(output_dir, 'dmrg1_energy', measure_mpo(ground1,H,N));
[ground,~] = dmrg_finite_2site(psi,H,N,8);
emit(output_dir, 'dmrg2_state', dense_state(ground));
emit(output_dir, 'dmrg2_energy', measure_mpo(ground,H,N));
% Infinite canonicalization from the original stateManipulations routine.
A = real(deterministic([3,3,2], 9));
emit(output_dir, 'uniform_input', A);
kwargs = struct('TFD',false);
[canonical,~,~] = canonicalForm({1,A,eye(3)}, 10, kwargs);
AL = canonical{2}; C = diag(sqrt(diag(canonical{3})));
AR = ncon({inv(C),AL,C},{[-1 1],[1 2 -3],[2 -2]});
emit(output_dir, 'uniform_schmidt', svd(C));
emit(output_dir, 'uniform_rho', physical_density(AL,C));
% A fixed-dimension original VUMPS iteration, then gauge-invariant outputs.
X=[0 1;1 0]; Z=[1 0;0 -1]; I=eye(2);
hmatrix=-kron(Z,Z)-0.35*(kron(X,I)+kron(I,X));
h=permute(reshape(hmatrix,[2,2,2,2]),[2,1,4,3]);
[ALt,ARt,Ct,~,~,~,~,~] = vtdvp(AL,AR,C,h,eye(3),eye(3),eye(3),eye(3),3,1,0.017);
emit(output_dir, 'uniform_tdvp_rho', physical_density(ALt,Ct));
emit(output_dir, 'uniform_tdvp_schmidt', svd(Ct)/norm(Ct(:)));
[AL,AR,C,~,~,~,~,residual] = vumps(AL,AR,C,h,eye(3),eye(3),eye(3),eye(3),3,1);
emit(output_dir, 'vumps_rho', physical_density(AL,C));
emit(output_dir, 'vumps_schmidt', svd(C)/norm(C(:)));
theta=ncon({AL,C,AR},{[-1 1 -3],[1 2],[2 -2 -4]});
htheta=update_AB(theta,h);
emit(output_dir, 'vumps_energy', dot(theta(:),htheta(:))/dot(theta(:),theta(:)));
emit(output_dir, 'vumps_residual', residual);
fid=fopen(fullfile(output_dir,'provenance.txt'),'w');
fprintf(fid,'Generated by MATLAB %s\nOriginal MATLAB routines; no Julia-generated references.\n',version);
fclose(fid);
fprintf('Exported MATLAB fixtures to %s\n',output_dir);
end

function A=deterministic(shape,offset)
k=(1:prod(shape))';
A=reshape(sin(0.037*k.^2+offset)+1i*cos(0.023*k.^2-offset),shape);
end
function emit(folder,name,A)
% Column-major complex arrays as two columns: real, imaginary.
writematrix([real(A(:)),imag(A(:))],fullfile(folder,[name '.csv']));
writematrix(size(A),fullfile(folder,[name '.shape']), 'FileType','text');
end
function state=dense_state(psi)
N=numel(psi); state=zeros(2^N,1);
for index=0:2^N-1
    bond=1;
    for n=1:N
        s=bitget(index,N-n+1)+1;
        bond=bond*psi{n}(:,:,s);
    end
    state(index+1)=bond;
end
end
function rho=physical_density(AL,C)
AC=ncon({AL,C},{[-1 1 -3],[1 -2]});
rho=ncon({AC,conj(AC)},{[1 2 -1],[1 2 -2]});
rho=rho/trace(rho);
end
